export const strings = { ru, ky } as const;
export type Word = keyof typeof ru;

export function t(locale: Locale, key: Word): string {
  const dict: Record<string, string | undefined> = strings[locale];
  const value = dict[key as string];
  if (value === undefined)
    throw new Error(
      `i18n: missing key "${String(key)}" for locale "${locale}"`,
    );
  return value;
}
