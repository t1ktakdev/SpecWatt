export function moduleString(locale: Locale, key: string): string {
  const value = strings[locale][key] ?? strings.ru[key] ?? key;
  return typeof value === "string" ? value : String(value);
}

/** "Найдено вопросов: {n}" with proper singular for 1. */
export function resultCount(locale: Locale, n: number): string {
  if (n === 1) return moduleString(locale, "searchResultOne");
  return moduleString(locale, "searchResultMany").replace("{n}", String(n));
}

/**
 * Local help search. Matches every query token against the question,
 * the keywords and the answer body in the active locale; the Cyrillic
 * letter ё is folded onto е so both spellings hit. Pure data + logic:
 * no React Native imports, unit-testable with node --test.
 */
const fold = (value: string) => value.toLowerCase().replace(/ё/g, "е");

export function normalizeQuery(query: string): string {
  return fold(query).trim().replace(/\s+/g, " ");
}

export function tokenize(query: string): string[] {
  return normalizeQuery(query).split(" ").filter(Boolean).slice(0, 8);
}

const WEIGHT_TITLE = 4;
const WEIGHT_KEYWORD = 2;
const WEIGHT_BODY = 1;

function score(article: HelpArticle, tokens: string[], locale: Locale) {
  const title = fold(article.title[locale]);
  const body = fold(article.body[locale].join(" "));
  const keywords = article.keywords[locale].map(fold);
  let total = 0;
  for (const token of tokens) {
    let best = 0;
    if (title.includes(token)) best = Math.max(best, WEIGHT_TITLE);
    if (keywords.some((k) => k.includes(token) || token.includes(k)))
      best = Math.max(best, WEIGHT_KEYWORD);
    if (body.includes(token)) best = Math.max(best, WEIGHT_BODY);
    // Every token must match somewhere; otherwise the article is irrelevant.
    if (best === 0) return 0;
    total += best;
  }
  return total;
}

/** Ordered results for a free-text query. Empty query returns no results: the UI shows the full grouped list instead. */
export function searchHelp(query: string, locale: Locale): HelpArticle[] {
  const tokens = tokenize(query);
  if (!tokens.length) return [];
  const scored: { article: HelpArticle; points: number }[] = [];
  helpArticles.forEach((article, index) => {
    const points = score(article, tokens, locale);
    if (points > 0) scored.push({ article, points: points - index * 1e-6 });
  });
  scored.sort((a, b) => b.points - a.points);
  return scored.map((x) => x.article);
}

/** Articles of one category in their canonical order; null returns everything. */
export function articlesInCategory(
  categoryId: HelpCategoryId | null,
): HelpArticle[] {
  return categoryId
    ? helpArticles.filter((a) => a.category === categoryId)
    : [...helpArticles];
}
